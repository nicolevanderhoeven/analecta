#!/usr/bin/env python3
"""Build the local, untracked name list the privacy check uses, from your own campaign notes.

Reads note titles, aliases and `player` fields from the campaign folder (read only) and writes
`.privacy-denylist` in the repository root, which git ignores. The names never leave your machine and
are never printed; only counts are. Monsters and items are left out (they are public Paizo content),
and so are short words and ordinary dictionary words, to avoid false alarms.

    scripts/build_denylist.py --source "<campaign notes folder>" [--out .privacy-denylist]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))
from analecta import frontmatter  # noqa: E402

SKIP_TYPES = {"monster", "item", "creature", "hazard", "spell", "feat"}
SESSION = re.compile(r"^\d{3,}_\d{8}")


def dictionary_words() -> set[str]:
    for p in ("/usr/share/dict/words", "/usr/share/dict/american-english"):
        f = Path(p)
        if f.is_file():
            return {w.strip() for w in f.read_text(errors="ignore").splitlines() if w.strip().islower()}
    return set()


def collect(source: Path) -> set[str]:
    names: set[str] = set()
    for p in source.rglob("*.md"):
        rel = p.relative_to(source)
        if any(part.startswith(".") for part in rel.parts) or SESSION.match(p.name) or p.is_symlink():
            continue
        entries, _ = frontmatter.split(p.read_text(encoding="utf-8", errors="replace")[:4000])
        meta = frontmatter.as_dict(entries)
        ntype = str(meta.get("type", "")).lower()
        if ntype in SKIP_TYPES:
            continue
        names.add(p.stem)
        aliases = meta.get("aliases")
        if isinstance(aliases, list):
            names.update(aliases)
        elif isinstance(aliases, str) and aliases:
            names.add(aliases)
        player = meta.get("player")
        if isinstance(player, str) and player:
            names.add(player)
    return names


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", required=True)
    ap.add_argument("--out", default=str(REPO_ROOT / ".privacy-denylist"))
    args = ap.parse_args()
    words = dictionary_words()
    kept = []
    for n in sorted(collect(Path(args.source).expanduser())):
        n = " ".join(n.replace("[[", "").replace("]]", "").split())
        if len(n) < 4 or n.lower() in words or n.lower().startswith("agenda"):
            continue
        kept.append(n)
    Path(args.out).write_text("# generated by scripts/build_denylist.py; local only, never commit\n"
                              + "\n".join(kept) + "\n", encoding="utf-8")
    print(f"wrote {len(kept)} names to the denylist")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
